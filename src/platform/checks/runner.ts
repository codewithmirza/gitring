interface RunContext {
  loader: WorkerLoader;
  key: string;
  files: Map<string, string>;
  timeoutMs: number;
  deadline: number;
}

type RunOutcome =
  | { kind: "ran"; cases: CheckCaseResult[] }
  | { kind: "load-error" | "timeout" | "bad-output"; message: string };

function assembleModules(files: Map<string, string>, run: string[], exclude: string[]): CheckModules {
  const excluded = new Set(exclude);
  const modules: Record<string, string> = {};
  for (const [path, content] of files) {
    if (isModulePath(path) && !path.startsWith(GENERATED_PREFIX) && !excluded.has(path)) modules[path] = content;
  }
  if (!(HARNESS_PATH in modules)) modules[HARNESS_PATH] = HARNESS_SOURCE;

  const tests = unique(run).filter((path) => path in modules && path !== HARNESS_PATH);
  const lines = [
    "// Generated by gitring: load the harness, then each test file after its marker, then run.",
    `import { __run } from ${JSON.stringify(`../${HARNESS_PATH}`)};`,
  ];
  tests.forEach((path, i) => {
    modules[`${GENERATED_PREFIX}file-${i}.js`] =
      `import { __setFile } from ${JSON.stringify(`../${HARNESS_PATH}`)};\n__setFile(${JSON.stringify(path)});\n`;
    lines.push(`import "./file-${i}.js";`, `import ${JSON.stringify(`../${path}`)};`);
  });
  lines.push("", "export default {", "  async fetch() {", "    return Response.json(await __run());", "  },", "};", "");
  modules[RUNNER_MODULE] = lines.join("\n");
  return { mainModule: RUNNER_MODULE, modules };
}

/** Split the requested test paths into runnable files and failed cases for the others. */
function triage(input: CheckFiles): { runnable: string[]; rejected: CheckCaseResult[] } {
  const runnable: string[] = [];
  const rejected: CheckCaseResult[] = [];
  for (const path of unique(input.testPaths)) {
    if (!input.files.has(path)) rejected.push(failedCase(path, "(missing file)", "The test file is not in the tree."));
    else if (!isModulePath(path) || path.startsWith(GENERATED_PREFIX) || path === HARNESS_PATH)
      rejected.push(failedCase(path, "(unsupported file)", "gitring runs only .js and .mjs test files."));
    else runnable.push(path);
  }
  return { runnable, rejected };
}

/** After a failed run of all files: load each file alone to find the files that fail. */
async function isolateFailures(ctx: RunContext, runnable: string[], failure: Exclude<RunOutcome, { kind: "ran" }>): Promise<CheckCaseResult[]> {
  const label = failure.kind === "timeout" ? "(timeout)" : "(load)";
  if (failure.kind !== "load-error" || runnable.length === 1 || runnable.length > MAX_FALLBACK_FILES) {
    return runnable.map((path) => failedCase(path, label, failure.message));
  }
  const cases: CheckCaseResult[] = [];
  for (const path of runnable) {
    const one = await runOnce(ctx, [path], runnable.filter((p) => p !== path));
    if (one.kind === "ran") cases.push(...one.cases);
    else cases.push(failedCase(path, one.kind === "timeout" ? "(timeout)" : "(load)", one.message));
  }
  return cases;
}

async function runOnce(ctx: RunContext, run: string[], exclude: string[]): Promise<RunOutcome> {
  const remaining = ctx.deadline - Date.now();
  const timedOut: RunOutcome = { kind: "timeout", message: `The checks did not finish in ${ctx.timeoutMs} ms.` };
  if (remaining <= 0) return timedOut;
  const id = `checks:${ctx.key}:${digest(JSON.stringify([RUNNER_VERSION, run, exclude]))}`;
  const work = (async (): Promise<RunOutcome> => {
    const stub = ctx.loader.get(id, () => {
      const code = assembleModules(ctx.files, run, exclude);
      return {
        compatibilityDate: CHECKS_COMPATIBILITY_DATE,
        mainModule: code.mainModule,
        modules: toLoaderModules(code.modules),
        globalOutbound: null,
        limits: { cpuMs: Math.min(ctx.timeoutMs, MAX_CPU_MS) },
      };
    });
    const res = await stub.getEntrypoint().fetch("http://checks.gitring.internal/run");
    const body = await res.text();
    if (!res.ok) return { kind: "bad-output", message: `The check runner answered ${res.status}: ${clip(body)}` };
    const cases = parseCases(body);
    if (!cases) return { kind: "bad-output", message: "The check runner did not return a list of results." };
    return { kind: "ran", cases: withEmptyFiles(cases, run) };
  })().catch((err: unknown): RunOutcome => ({ kind: "load-error", message: loadMessage(err) }));

  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<RunOutcome>((resolve) => {
    timer = setTimeout(() => resolve(timedOut), remaining);
  });
  try {
    return await Promise.race([work, timeout]);
  } finally {
    clearTimeout(timer);
  }
}

function parseCases(body: string): CheckCaseResult[] | null {
  let data: unknown;
  try {
    data = JSON.parse(body);
  } catch {
    return null;
  }
  if (!Array.isArray(data)) return null;
  return data.map((raw): CheckCaseResult => {
    const c = (raw ?? {}) as Record<string, unknown>;
    const ok = c.ok === true;
    const ms = typeof c.ms === "number" && Number.isFinite(c.ms) ? Math.max(0, c.ms) : 0;
    const result: CheckCaseResult = { file: String(c.file ?? ""), name: String(c.name ?? "(unnamed test)"), ok, ms };
    if (!ok) result.error = clip(String(c.error ?? "The test failed."));
    return result;
  });
}

/** A requested file that registers no tests counts as a failure: it verifies nothing. */
function withEmptyFiles(cases: CheckCaseResult[], run: string[]): CheckCaseResult[] {
  const seen = new Set(cases.map((c) => c.file));
  const empty = run.filter((path) => !seen.has(path)).map((path) => failedCase(path, "(no tests)", "The file registers no tests."));
  return [...cases, ...empty];
}

function failedCase(file: string, name: string, error: string): CheckCaseResult {
  return { file, name, ok: false, error: clip(error), ms: 0 };
}

/** "Failed to start Worker:\nUncaught SyntaxError: …\n  at tests/x.test.js:1:2" → one line. */
function loadMessage(err: unknown): string {
  const raw = err instanceof Error ? err.message : String(err);
  return clip(raw.replace(/^Failed to start Worker:\s*/i, "").replace(/\s*\n\s*/g, " ").trim() || "Unknown error.");
}

function clip(text: string): string {
  return text.length > MAX_TEXT ? `${text.slice(0, MAX_TEXT)}…` : text;
}

function unique(paths: string[]): string[] {
  return [...new Set(paths)];
}

/** FNV-1a, 32 bit, as 8 hex characters. Not for security: it only separates loader ids. */
function digest(text: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
}

function newCheckRunId(): string {
  return `chk_${crypto.randomUUID().replace(/-/g, "").slice(0, 16)}`;
}
