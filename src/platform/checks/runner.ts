/**
 * Check runner: runs the executable checks of an intent inside a Dynamic Worker (Worker Loader).
 *
 * The tree under test becomes the module map of the Dynamic Worker: every .js/.mjs file keeps its
 * repo path as its module name ("src/render.js", "tests/x.test.js"). gitring adds a generated main
 * module ("__gitring__/runner.js") that imports the harness, then each test file after a tiny
 * marker module that calls __setFile(path), then runs all tests and answers with the results as JSON.
 *
 * The Dynamic Worker has no network (globalOutbound: null) and a CPU limit. workerd compiles every
 * module of the map at startup, so a syntax error in any .js file fails the whole load. When a load
 * fails and more than one test file was requested, the runner loads each test file alone (without
 * the other requested test files) to show which file fails.
 */
import type { CheckCaseResult, CheckRun } from "../../core/types";

export interface CheckFiles {
  /** All text files of the tree: repo-relative path → content. */
  files: Map<string, string>;
  /** The test files to run, in order, for example ["tests/app.test.js", "tests/search.test.js"]. */
  testPaths: string[];
}

export interface CheckModules {
  mainModule: string;
  modules: Record<string, string>;
}

export interface RunChecksOptions {
  /** Total time budget, fallback runs included. Default 10000 ms. */
  timeoutMs?: number;
  /** "attempt" (default) = the attempt alone; "composed" = main + attempt. */
  scope?: CheckRun["scope"];
  /** CheckRun id. Default: a new random id. */
  id?: string;
}

export const CHECKS_COMPATIBILITY_DATE = "2026-10-01";
export const RUNNER_MODULE = "__gitring__/runner.js";
export const HARNESS_PATH = "harness/test.js";
/** Bump when the generated modules change, so that no isolate with old code is reused. */
export const RUNNER_VERSION = "1";

const GENERATED_PREFIX = "__gitring__/";
const DEFAULT_TIMEOUT_MS = 10_000;
const MAX_CPU_MS = 30_000;
const MAX_FALLBACK_FILES = 12;
const MAX_TEXT = 2_000;

/**
 * The test harness that gitring injects when a tree has no harness/test.js.
 * Same source as demo/repo/harness/test.js (a test keeps the two equal).
 */
export const HARNESS_SOURCE = String.raw`// Saltmarsh Books test harness: a tiny test API with no dependencies.
// It runs in Node (tests/run.mjs) and in workerd (the gitring check runner).
//
//   test(name, fn)    Register a test. fn can be async.
//   expect(actual)    toBe, toEqual, toContain, toMatch, toBeTruthy, toBeFalsy, toThrow, and .not
//   __setFile(path)   The runner calls this before it loads each test file.
//   __run()           Run every registered test. Returns [{ file, name, ok, error, ms }].
//
// Do not edit this file. gitring injects the same harness into repos that have none.

const TEST_TIMEOUT_MS = 3000;
const registered = [];
let currentFile = "";

export function __setFile(path) {
  currentFile = String(path);
}

export function test(name, fn) {
  if (typeof fn !== "function") throw new TypeError("test(" + JSON.stringify(String(name)) + ") needs a function");
  registered.push({ file: currentFile, name: String(name), fn: fn });
}

export async function __run() {
  const results = [];
  for (const t of registered) {
    const started = now();
    let error;
    try {
      await withTimeout(t.fn, TEST_TIMEOUT_MS);
    } catch (e) {
      error = describeError(e);
    }
    const ms = Math.round((now() - started) * 100) / 100;
    if (error === undefined) results.push({ file: t.file, name: t.name, ok: true, ms: ms });
    else results.push({ file: t.file, name: t.name, ok: false, error: error, ms: ms });
  }
  return results;
}

export function expect(actual) {
  return matchers(actual, false);
}

class AssertionError extends Error {
  constructor(message) {
    super(message);
    this.name = "AssertionError";
  }
}

function matchers(actual, negated) {
  function assert(pass, description, subject) {
    if (pass !== negated) return;
    const shown = subject === undefined ? show(actual) : subject;
    throw new AssertionError("expected " + shown + (negated ? " not " : " ") + description);
  }
  const api = {
    toBe(expected) {
      assert(Object.is(actual, expected), "to be " + show(expected));
    },
    toEqual(expected) {
      assert(deepEqual(actual, expected), "to equal " + show(expected));
    },
    toContain(item) {
      assert(contains(actual, item), "to contain " + show(item), around(actual, item));
    },
    toMatch(pattern) {
      assert(matches(actual, pattern), "to match " + show(pattern));
    },
    toBeTruthy() {
      assert(Boolean(actual), "to be truthy");
    },
    toBeFalsy() {
      assert(!actual, "to be falsy");
    },
    // For an async function, await the result: await expect(fn).toThrow("message").
    toThrow(expected) {
      return throws(actual, expected, negated);
    },
  };
  if (!negated) {
    Object.defineProperty(api, "not", {
      get: function () {
        return matchers(actual, true);
      },
    });
  }
  return api;
}

function throws(fn, expected, negated) {
  if (typeof fn !== "function") throw new TypeError("toThrow needs a function, got " + show(fn));
  let result;
  try {
    result = fn();
  } catch (error) {
    return judgeThrow(true, error, expected, negated);
  }
  if (result && typeof result.then === "function") {
    return result.then(
      function () {
        judgeThrow(false, undefined, expected, negated);
      },
      function (error) {
        judgeThrow(true, error, expected, negated);
      },
    );
  }
  return judgeThrow(false, undefined, expected, negated);
}

function judgeThrow(threw, error, expected, negated) {
  const pass = threw && errorMatches(error, expected);
  if (pass !== negated) return undefined;
  const wanted = expected === undefined ? "to throw" : "to throw " + show(expected);
  const got = threw ? " (it threw " + describeError(error) + ")" : " (it did not throw)";
  throw new AssertionError("expected the function " + (negated ? "not " : "") + wanted + got);
}

function errorMatches(error, expected) {
  if (expected === undefined) return true;
  const message = error && error.message !== undefined ? String(error.message) : String(error);
  if (typeof expected === "string") return message.includes(expected);
  if (expected instanceof RegExp) return message.search(expected) !== -1;
  if (typeof expected === "function") return error instanceof expected;
  if (expected instanceof Error) return message === expected.message;
  return false;
}

function contains(actual, item) {
  if (typeof actual === "string") return typeof item === "string" && actual.includes(item);
  if (Array.isArray(actual)) return actual.includes(item);
  if (actual instanceof Set) return actual.has(item);
  if (actual && typeof actual[Symbol.iterator] === "function") return Array.from(actual).includes(item);
  throw new TypeError("toContain needs a string or an array, got " + show(actual));
}

function matches(actual, pattern) {
  if (typeof actual !== "string") throw new TypeError("toMatch needs a string, got " + show(actual));
  if (pattern instanceof RegExp) return actual.search(pattern) !== -1;
  return actual.includes(String(pattern));
}

function deepEqual(a, b) {
  if (Object.is(a, b)) return true;
  if (typeof a !== "object" || typeof b !== "object" || a === null || b === null) return false;
  if (Array.isArray(a) || Array.isArray(b)) {
    if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) return false;
    return a.every(function (value, i) {
      return deepEqual(value, b[i]);
    });
  }
  if (a instanceof Date || b instanceof Date) {
    return a instanceof Date && b instanceof Date && a.getTime() === b.getTime();
  }
  if (a instanceof RegExp || b instanceof RegExp) return String(a) === String(b);
  if (a instanceof Map || b instanceof Map) return mapsEqual(a, b);
  if (a instanceof Set || b instanceof Set) return setsEqual(a, b);
  const keysA = definedKeys(a);
  const keysB = definedKeys(b);
  if (keysA.length !== keysB.length) return false;
  return keysA.every(function (key) {
    return Object.prototype.hasOwnProperty.call(b, key) && deepEqual(a[key], b[key]);
  });
}

function mapsEqual(a, b) {
  if (!(a instanceof Map) || !(b instanceof Map) || a.size !== b.size) return false;
  for (const [key, value] of a) {
    if (!b.has(key) || !deepEqual(value, b.get(key))) return false;
  }
  return true;
}

function setsEqual(a, b) {
  if (!(a instanceof Set) || !(b instanceof Set) || a.size !== b.size) return false;
  for (const value of a) {
    if (!b.has(value)) return false;
  }
  return true;
}

function definedKeys(object) {
  return Object.keys(object).filter(function (key) {
    return object[key] !== undefined;
  });
}

function show(value) {
  if (typeof value === "string") return clip(JSON.stringify(value));
  if (typeof value === "number") return Object.is(value, -0) ? "-0" : String(value);
  if (typeof value === "function") return "[Function " + (value.name || "anonymous") + "]";
  if (typeof value === "bigint") return String(value) + "n";
  if (typeof value === "symbol" || value === undefined) return String(value);
  if (value instanceof RegExp) return String(value);
  if (value instanceof Error) return value.name + ": " + value.message;
  if (value instanceof Map) return "Map(" + value.size + ")";
  if (value instanceof Set) return "Set(" + value.size + ")";
  try {
    const json = JSON.stringify(value);
    return json === undefined ? String(value) : clip(json);
  } catch (e) {
    return String(value);
  }
}

function clip(text) {
  const max = 160;
  if (text.length <= max) return text;
  return text.slice(0, max) + "… (" + text.length + " chars)";
}

// For a long string that contains item: show the text around item, not the start of the string.
function around(actual, item) {
  if (typeof actual !== "string" || typeof item !== "string" || actual.length <= 160) return undefined;
  const at = actual.indexOf(item);
  if (at < 0) return undefined;
  const start = Math.max(0, at - 60);
  const inner = JSON.stringify(actual.slice(start, at + item.length + 60)).slice(1, -1);
  return '"…' + inner + '…" (' + actual.length + " chars)";
}

function describeError(error) {
  if (error instanceof AssertionError) return error.message;
  if (error instanceof Error) return error.name + ": " + error.message;
  return "Thrown: " + show(error);
}

function withTimeout(fn, ms) {
  let timer;
  const timeout = new Promise(function (resolve, reject) {
    timer = setTimeout(function () {
      const error = new Error("The test did not finish in " + ms + " ms.");
      error.name = "TimeoutError";
      reject(error);
    }, ms);
  });
  return Promise.race([Promise.resolve().then(fn), timeout]).finally(function () {
    clearTimeout(timer);
  });
}

function now() {
  if (typeof performance !== "undefined" && performance && typeof performance.now === "function") return performance.now();
  return Date.now();
}
`;

/** Files that become modules: .js and .mjs. */
export function isModulePath(path: string): boolean {
  return /\.m?js$/.test(path);
}

/**
 * Module map for the Worker Loader. workerd needs a ".js" (or ".py") name for a plain string module,
 * so a ".mjs" module goes in as { js: source }.
 */
export function toLoaderModules(modules: Record<string, string>): Record<string, string | WorkerLoaderModule> {
  const out: Record<string, string | WorkerLoaderModule> = {};
  for (const [name, source] of Object.entries(modules)) out[name] = name.endsWith(".mjs") ? { js: source } : source;
  return out;
}

/**
 * Build the module map that runs `testPaths` against `files`. Pure.
 * Test paths that are absent or are not .js/.mjs files are skipped (runChecks reports them as failures).
 */
export function buildCheckModules(input: CheckFiles): CheckModules {
  return assembleModules(input.files, input.testPaths, []);
}

/**
 * Run the checks in a Dynamic Worker and return a CheckRun.
 * `key` must identify the content of `files` (for example a tree hash). The loader id is
 * `checks:<key>:<digest of the test list>`, so one tree can run different test lists safely.
 */
export async function runChecks(loader: WorkerLoader, key: string, input: CheckFiles, opts: RunChecksOptions = {}): Promise<CheckRun> {
  const started = Date.now();
  const timeoutMs = opts.timeoutMs ?? DEFAULT_TIMEOUT_MS;
  const ctx: RunContext = { loader, key, files: input.files, timeoutMs, deadline: started + timeoutMs };
  const { runnable, rejected } = triage(input);
  const cases: CheckCaseResult[] = [...rejected];
  let error: string | undefined;

  if (runnable.length > 0) {
    const all = await runOnce(ctx, runnable, []);
    if (all.kind === "ran") {
      cases.push(...all.cases);
    } else {
      error = all.kind === "load-error" ? `The checks did not load: ${all.message}` : all.message;
      cases.push(...(await isolateFailures(ctx, runnable, all)));
    }
  }

  const failed = cases.filter((c) => !c.ok).length;
  return {
    id: opts.id ?? newCheckRunId(),
    subject: key,
    scope: opts.scope ?? "attempt",
    ok: error === undefined && failed === 0,
    passed: cases.length - failed,
    failed,
    cases,
    ms: Date.now() - started,
    at: started,
    ...(error === undefined ? {} : { error }),
  };
}

/** A short content key for a tree: SHA-256 over the sorted paths and contents (hex, 20 chars). */
export async function contentKey(files: Map<string, string>): Promise<string> {
  const encoder = new TextEncoder();
  const parts: Uint8Array[] = [];
  for (const path of [...files.keys()].sort()) {
    parts.push(encoder.encode(`${path}\0${files.get(path)}\0`));
  }
  const total = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let offset = 0;
  for (const part of parts) {
    total.set(part, offset);
    offset += part.length;
  }
  const hash = new Uint8Array(await crypto.subtle.digest("SHA-256", total));
  return [...hash].map((b) => b.toString(16).padStart(2, "0")).join("").slice(0, 20);
}

